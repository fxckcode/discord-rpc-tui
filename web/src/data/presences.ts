export const categories = [...new Set(presences.map(p => p.category))].sort();

export const allTags = [...new Set(presences.flatMap(p => p.tags))].sort();

export function getPresenceById(id: string): Presence | undefined {
  return presences.find(p => p.id === id);
}

export function getPresencesByCategory(category: string): Presence[] {
  return presences.filter(p => p.category === category);
}

export function getFeaturedPresences(): Presence[] {
  return presences.filter(p => p.featured);
}
